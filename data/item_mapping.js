window.findExchangeItem = function(product) {
  if (window.EXCHANGE_ITEMS_MAP[product]) return window.EXCHANGE_ITEMS_MAP[product];
  for (var key in window.EXCHANGE_ITEMS_MAP) {
    if (window.EXCHANGE_ITEMS_MAP[key].name === product) return window.EXCHANGE_ITEMS_MAP[key];
  }
  return {image: '', quality: 'gold', name: product};
};

window.ITEM_MAPPING = {};
(function(){
  if(!window.EXCHANGE_ITEMS_MAP) return;
  for (var key in window.EXCHANGE_ITEMS_MAP) {
    if (window.EXCHANGE_ITEMS_MAP.hasOwnProperty(key)) {
      var item = window.EXCHANGE_ITEMS_MAP[key];
      if (item && item.name) {
        window.ITEM_MAPPING[item.name] = {image: item.image, quality: item.quality, showcase: item.showcase};
      }
    }
  }
})();

